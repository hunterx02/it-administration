async def import_data(entity: str, request: Request, file: UploadFile | None = File(None), url: str = Form(""),
                      sheet: str = Form(""), commit: bool = Form(False), p: Principal = Depends(current_principal),
                      db: Session = Depends(get_db)) -> dict:
    d = _entity(entity)
    if not p.can(d["create"]):
        raise forbid("ليس لديك صلاحية الاستيراد هنا")
    if file is not None and file.filename:
        data, fname = await file.read(MAX_BYTES + 1), file.filename
        if len(data) > MAX_BYTES:
            raise bad("الملف أكبر من 5 ميجا")
        if not fname.lower().endswith((".xlsx", ".csv")):
            raise bad("الملف لازم يكون xlsx أو csv")
    elif url.strip():
        data, fname = fetch_url(url), "sheet.csv"
    else:
        raise bad("ارفع ملف أو حط لينك شيت")
    recs = to_records(read_table(data, fname, sheet or None), d["keys"])
    counts = {"new": 0, "update": 0, "same": 0, "error": 0}
    rows = []
    db.info["pending_passwords"] = []
    db.info["pending_mail_passwords"] = []
    sp = db.begin_nested()
    for n, rec in recs:
        before = len(db.info["pending_passwords"])
        before_mail = len(db.info["pending_mail_passwords"])
        try:
            with db.begin_nested():
                status, key, msg = d["import"](db, p, rec, p.user.id)
        except RowError as e:
            status, key, msg = "error", "", str(e)
            del db.info["pending_passwords"][before:]  # row rolled back -> drop its password too
            del db.info["pending_mail_passwords"][before_mail:]
        counts[status] += 1
        if len(rows) < 500:
            rows.append({"row": n, "status": status, "key": key, "message": msg})
    pending = db.info.pop("pending_passwords", [])
    pending_mail = db.info.pop("pending_mail_passwords", [])
    if commit:
        sp.commit()
        audit.record(db, "import.committed", actor_id=p.user.id, entity=entity, entity_id=fname,
                     details={"counts": counts, "source": "url" if url.strip() else "file",
                              "passwords_stored": len(pending) + len(pending_mail)}, ip=client_ip(request))
        db.commit()
        if pending_mail:
            from ..secrets_store import store_for
            from .mailboxes import PW_PREFIX as MAIL_PW
            store = store_for(request.app.state.settings)
            for mid, pw in pending_mail:
                m = db.get(Mailbox, mid)
                if m is not None:
                    store.set(MAIL_PW + m.id, pw)
                    m.vault_ref = "vault:" + MAIL_PW + m.id
            db.commit()
        if pending:
            from ..secrets_store import store_for
            from .assets import save_device_password
            store = store_for(request.app.state.settings)
            for asset_id, pw in pending:
                a = db.get(Asset, asset_id)
                if a is not None:
                    save_device_password(store, a, pw)
            db.commit()
    else:
        sp.rollback()
        db.rollback()
    return {"entity": entity, "committed": commit, "total": len(recs), "counts": counts, "rows": rows}


@router.get("/export/{entity}")
def export_data(entity: str, request: Request, fmt: str = Query("xlsx", pattern="^(xlsx|csv)$"),
                company_id: str | None = None, p: Principal = Depends(current_principal),
                db: Session = Depends(get_db)) -> Response:
    d = _entity(entity)
    if not p.can(d["view"]):
        raise forbid("ليس لديك صلاحية التصدير هنا")
    q = select(d["model"]).order_by(d["order"])
    if d["company_col"] is not None:
        q = scope_filter(q, p, d["company_col"])
        if company_id:
            q = q.where(d["company_col"] == company_id)
    rows = [[safe_cell(v if not isinstance(v, (date, datetime)) else v.isoformat()) for v in d["export"](db, o)]
            for o in db.scalars(q)]
    audit.record(db, "export.data", actor_id=p.user.id, entity=entity, entity_id=fmt, details={"rows": len(rows)},
                 ip=client_ip(request))
    db.commit()
    stamp = now().strftime("%Y%m%d-%H%M")
    if fmt == "csv":
        buf = io.StringIO()
        w = csv.writer(buf)
        w.writerow(d["head"])
        w.writerows(rows)
        return Response("﻿" + buf.getvalue(), media_type="text/csv; charset=utf-8",
                        headers={"Content-Disposition": f'attachment; filename="{entity}-{stamp}.csv"'})
    from openpyxl import Workbook
    from openpyxl.styles import Font
    wb = Workbook()
    ws = wb.active
    ws.title = d["label"]
    ws.sheet_view.rightToLeft = True
    ws.append(d["head"])
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in rows:
        ws.append(["" if v is None else v for v in r])
    for i, h in enumerate(d["head"], 1):
        ws.column_dimensions[ws.cell(1, i).column_letter].width = max(12, len(h) + 4)
    buf = io.BytesIO()
    wb.save(buf)
    return Response(buf.getvalue(), media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                    headers={"Content-Disposition": f'attachment; filename="{entity}-{stamp}.xlsx"'})

