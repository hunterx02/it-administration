def mail_import(db: Session, p: Principal, r: dict, actor: str) -> tuple[str, str, str]:
    from .mailboxes import MailboxIn, create_mailbox, norm_address
    addr_raw = r.get("الإيميل", "").strip()
    if not addr_raw:
        raise RowError("الإيميل مطلوب")
    try:
        addr = norm_address(addr_raw)
    except Exception:  # noqa: BLE001
        raise RowError(f"إيميل غير صحيح: {addr_raw}") from None
    code = r.get("كود الإيميل", "").strip()
    m = db.scalar(select(Mailbox).where(Mailbox.address == addr))
    if m is None and code:
        m = db.scalar(select(Mailbox).where(Mailbox.code == code))
    pw = next((str(r[h]).strip() for h in PW_HEADERS if h in r and str(r[h]).strip() not in PW_PLACEHOLDERS), "")
    vals = {"provider": r.get("المزود", "").strip(), "plan": r.get("الباقة", "").strip(),
            "aliases": r.get("Aliases", "").strip(), "forwarding": r.get("تحويل إلى", "").strip(),
            "recovery": r.get("إيميل الاسترداد", "").strip(), "notes": r.get("ملاحظات", "").strip()}
    kind = MAIL_KIND_IN.get(r.get("النوع", "").strip().lower() or r.get("النوع", "").strip(), "")
    mfa = r.get("MFA", "").strip().lower() in YES
    pw_note = ""
    if pw:
        if p.can("technical:view_secrets"):
            pw_note = " · 🔑 الباسورد هيتحفظ مشفّر"
        else:
            pw, pw_note = "", " · الباسورد اتجاهل (مش عندك صلاحية الأسرار)"
    if m is None:
        c = _company(db, p, r.get("الشركة", ""))
        emp = None
        ecode, ename = r.get("الكود الوظيفي", "").strip(), r.get("اسم الموظف", "").strip()
        if ecode:
            emp = db.scalar(select(Employee).where(Employee.employee_code == ecode))
        elif ename:
            emp = db.scalar(select(Employee).where(Employee.company_id == c.id, Employee.full_name == ename))
        if (ecode or ename) and emp is None:
            raise RowError(f"الموظف «{ecode or ename}» مش موجود — ضيفه الأول أو سيب الخانة فاضية")
        if emp is not None and (emp.custody_frozen or emp.status in ("offboarding", "exited")):
            raise RowError(f"الموظف {emp.full_name} عليه إخلاء طرف — مينفعش يستلم إيميل")
        try:
            new = create_mailbox(db, p, MailboxIn(company_id=c.id, address=addr, code=code,
                                                  employee_id=emp.id if emp else None, kind=kind or "personal",
                                                  mfa_enabled=mfa, is_primary=r.get("أساسي", "").strip().lower() in YES,
                                                  **vals))
        except Exception as e:  # noqa: BLE001
            raise RowError(getattr(e, "detail", None) or str(e)) from None
        if pw:
            db.info.setdefault("pending_mail_passwords", []).append((new.id, pw))
        return "new", new.code, ("إيميل جديد" + (f" لـ {emp.full_name}" if emp else "")) + pw_note
    changed: list = []
    for k, v in vals.items():
        _set(m, k, v, changed)
    if kind and kind != m.kind:
        m.kind = kind
        changed.append("kind")
    if mfa and not m.mfa_enabled:
        m.mfa_enabled = True
        changed.append("mfa")
    if pw:
        db.info.setdefault("pending_mail_passwords", []).append((m.id, pw))
    note = ""
    if (r.get("الكود الوظيفي", "").strip() or r.get("اسم الموظف", "").strip()) and not m.employee_id:
        note = " · ربط الموظف من الملف مش بيتنفذ على إيميل موجود — استخدم «تسليم» في صفحة الإيميلات"
    if changed:
        m.version += 1
        return "update", m.code, "اتحدث: " + "، ".join(changed) + note + pw_note
    return "same", m.code, ("مفيش تغيير" + note + pw_note) if (note or pw_note) else "مفيش تغيير"


