def asset_import(db: Session, p: Principal, r: dict, actor: str) -> tuple[str, str, str]:
    code = r.get("كود الأصل", "").strip()
    acc = {k: str(r.get(lbl, "")).strip().lower() in TRUE for k, lbl in ACC if lbl in r}
    if code:
        a = db.scalar(select(Asset).where(Asset.code == code))
        if a is None:
            raise RowError("كود مش موجود — سيب الكود فاضي للأصول الجديدة (النظام بيولّده)")
        allowed = p.company_ids()
        if allowed is not None and a.company_id not in allowed:
            raise RowError("الأصل خارج صلاحيتك")
        changed: list = []
        for h, f in ASSET_SIMPLE.items():
            if h in r:
                _set(a, f, r[h], changed)
        if "القسم" in r and r["القسم"]:
            _set(a, "department_id", _dept(db, a.company_id, r["القسم"]), changed)
        if acc and acc != {k: bool((a.accessories or {}).get(k)) for k in acc}:
            a.accessories = {**(a.accessories or {}), **acc}
            changed.append("accessories")
        note = ""
        holder = r.get("اسم الموظف", "").strip()
        if holder and holder != _emp_name(db, a.holder_employee_id):
            note = " · تغيير المستلم من الملف مش بيتنفذ — استخدم «تسليم» في صفحة الأصل"
        pw_note = _queue_password(db, p, a, r)
        note += pw_note
        if pw_note.startswith(" · 🔑"):
            changed.append("كلمة المرور")
        if changed:
            a.version += 1
            a.source = "import"
            return "update", code, "اتحدث: " + "، ".join(changed) + note
        return "same", code, "مفيش تغيير" + note
    c = _company(db, p, r.get("الشركة", ""))
    cat = r.get("الفئة", "").strip()
    if not cat or db.get(AssetCategory, cat) is None:
        raise RowError(f"الفئة «{cat}» مش موجودة")
    fields = {f: r[h] for h, f in ASSET_SIMPLE.items() if r.get(h)}
    fields["department_id"] = _dept(db, c.id, r.get("القسم", ""))
    fields["accessories"] = acc
    try:
        a = create_asset(db, company_id=c.id, category_code=cat, actor_id=actor, source="import", **fields)
    except Exception as e:  # noqa: BLE001
        raise RowError(getattr(e, "detail", str(e))) from None
    msg = "أصل جديد"
    holder = r.get("اسم الموظف", "").strip()
    if holder:
        emp = db.scalar(select(Employee).where(Employee.company_id == c.id, Employee.full_name == holder))
        if emp is None:
            msg += f" · الموظف «{holder}» مش موجود — اتسجل في المخزن"
        else:
            try:
                do_handover(db, a, emp.id, actor, source="import")
                msg += f" · مسلّم لـ {holder}"
            except Exception as e:  # noqa: BLE001
                msg += f" · ما اتسلمش: {getattr(e, 'detail', e)}"
    msg += _queue_password(db, p, a, r)
    return "new", a.code, msg


