def google_csv_url(url: str) -> str:
    m = re.match(r"^https://docs\.google\.com/spreadsheets/d/([A-Za-z0-9_-]+)", url.strip())
    if not m:
        raise bad("اللينك لازم يكون لينك Google Sheets (https://docs.google.com/spreadsheets/d/...)")
    gid = re.search(r"[#&?]gid=(\d+)", url)
    return f"https://docs.google.com/spreadsheets/d/{m.group(1)}/export?format=csv" + (f"&gid={gid.group(1)}" if gid else "")


def fetch_url(url: str) -> bytes:
    src = google_csv_url(url)
    try:
        with httpx.Client(timeout=20, follow_redirects=True) as c:
            r = c.get(src)
    except httpx.HTTPError as e:
        raise bad(f"تعذر الوصول للشيت: {e}") from None
    host = r.url.host or ""
    if not (host.endswith("google.com") or host.endswith("googleusercontent.com")):
        raise bad("تحويل لموقع غير متوقع — اتلغى")
    if r.status_code in (401, 403) or "accounts.google.com" in str(r.url) or "text/html" in r.headers.get("content-type", ""):
        raise bad("الشيت مش متاح للقراءة باللينك. شاركه «Anyone with the link — Viewer» أو استخدم موصل Google من الربط والأتمتة")
    if r.status_code != 200:
        raise bad(f"Google رجّع {r.status_code}")
    if len(r.content) > MAX_BYTES:
        raise bad("الشيت أكبر من 5 ميجا")
    return r.content


def read_table(data: bytes, filename: str, sheet: str | None) -> list[list[str]]:
    name = filename.lower()
    if name.endswith(".xlsx"):
        from openpyxl import load_workbook
        wb = load_workbook(io.BytesIO(data), read_only=True, data_only=True)
        ws = wb[sheet] if sheet and sheet in wb.sheetnames else wb[wb.sheetnames[0]]
        out = []
        for r in ws.iter_rows(values_only=True):
            out.append(["" if v is None else (v.date().isoformat() if isinstance(v, datetime) else
                                               v.isoformat() if isinstance(v, date) else str(v)).strip() for v in r])
        return out
    text = data.decode("utf-8-sig", errors="replace")
    return [[c.strip() for c in r] for r in csv.reader(io.StringIO(text))]


def to_records(grid: list[list[str]], key_headers: list[str]) -> list[tuple[int, dict]]:
    """Find the header row (first row containing any expected header) and return (sheet_row_no, dict)."""
    hi = next((i for i, r in enumerate(grid[:20]) if any(h in r for h in key_headers)), None)
    if hi is None:
        raise bad("مش لاقي صف العناوين. الأعمدة المتوقعة: " + "، ".join(key_headers[:6]))
    head = grid[hi]
    recs = []
    for i, r in enumerate(grid[hi + 1:], start=hi + 2):
        rec = {h: (r[j] if j < len(r) else "") for j, h in enumerate(head) if h}
        if any(str(v).strip() for v in rec.values()):
            recs.append((i, rec))
    return recs


# ---------------------------------------------------------------- helpers
def _company(db: Session, p: Principal, name: str) -> Company:
    name = (name or "").strip()
    if not name:
        raise RowError("الشركة مطلوبة")
    c = db.scalar(select(Company).where(func.lower(Company.name) == name.lower()))
    if c is None:
        raise RowError(f"الشركة «{name}» مش موجودة — ضيفها من إدارة النظام الأول")
    allowed = p.company_ids()
    if allowed is not None and c.id not in allowed:
        raise RowError("الشركة خارج صلاحيتك")
    return c


def _dept(db: Session, company_id: str, name: str) -> str | None:
    name = (name or "").strip()
    if not name:
        return None
    d = db.scalar(select(Department).where(Department.company_id == company_id, func.lower(Department.name) == name.lower()))
    if d is None:
        d = Department(company_id=company_id, name=name)
        db.add(d)
        db.flush()
    return d.id


def _num(v: Any) -> float | None:
    s = str(v or "").replace(",", "").strip()
    if not s:
        return None
    try:
        return float(s)
    except ValueError:
        raise RowError(f"رقم غير صالح: {v}") from None


def _date(v: Any) -> date | None:
    s = str(v or "").strip()[:10]
    if not s:
        return None
    for fmt in ("%Y-%m-%d", "%d/%m/%Y", "%m/%d/%Y"):
        try:
            return datetime.strptime(s, fmt).date()
        except ValueError:
            pass
    raise RowError(f"تاريخ غير مفهوم: {v}")


def _emp_name(db: Session, eid: str | None) -> str:
    e = db.get(Employee, eid) if eid else None
    return e.full_name if e else ""


def _company_name(db: Session, cid: str) -> str:
    c = db.get(Company, cid)
    return c.name if c else ""


def _dept_name(db: Session, did: str | None) -> str:
    d = db.get(Department, did) if did else None
    return d.name if d else ""


def _set(obj: Any, field: str, value: Any, changed: list) -> None:
    if value is None or value == "":
        return
    if getattr(obj, field) != value:
        setattr(obj, field, value)
        changed.append(field)


