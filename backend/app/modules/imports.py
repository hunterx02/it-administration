def _queue_password(db: Session, p: Principal, a: Asset, r: dict) -> str:
    """Passwords from the sheet are encrypted into the secrets store only after a confirmed commit."""
    pw = next((str(r[h]).strip() for h in PW_HEADERS if h in r and str(r[h]).strip() not in PW_PLACEHOLDERS), "")
    if not pw:
        return ""
    if not p.can("assets:view_secrets"):
        return " · الباسورد اتجاهل (مش عندك صلاحية كلمات مرور الأجهزة)"
    db.info.setdefault("pending_passwords", []).append((a.id, pw))
    return " · 🔑 الباسورد هيتحفظ مشفّر"
